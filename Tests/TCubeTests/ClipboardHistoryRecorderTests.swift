import AppKit
import Combine
import CubeCore
import Testing
@testable import TCube

@MainActor
struct ClipboardHistoryRecorderTests {
    @Test func enableBaselinesCurrentSequenceAndReadsTextOnlyForNewChanges() {
        let source = HistoryReaderFixture()
        source.text = "before enable"
        var captured: [String] = []
        let recorder = ClipboardHistoryRecorder(reader: source, schedule: nil) { captured.append($0) }
        recorder.poll()
        recorder.start()
        recorder.poll()
        #expect(source.textReads == 0)
        #expect(source.typeReads == 0)
        source.changeCount += 1
        source.text = "new text"
        recorder.poll()
        recorder.poll()
        #expect(captured == ["new text"])
        #expect(source.textReads == 1)
        #expect(source.typeReads == 1)
    }

    @Test func pauseAndResumeSkipClipboardChangesWhilePaused() {
        let source = HistoryReaderFixture()
        var captured: [String] = []
        let recorder = ClipboardHistoryRecorder(reader: source, schedule: nil) { captured.append($0) }
        recorder.start()
        recorder.stop()
        source.changeCount += 1
        source.text = "paused"
        recorder.poll()
        recorder.start()
        recorder.poll()
        #expect(captured.isEmpty)
        #expect(source.textReads == 0)
        source.changeCount += 1
        source.text = "resumed"
        recorder.poll()
        #expect(captured == ["resumed"])
    }

    @Test func exclusionMarkersAreInspectedBeforeAnyTextRead() {
        let source = HistoryReaderFixture()
        let recorder = ClipboardHistoryRecorder(reader: source, schedule: nil) { _ in Issue.record("Excluded clipboard was captured") }
        recorder.start()
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "public.file-url", "NSFilenamesPboardType"] {
            source.changeCount += 1
            source.types = [.string, NSPasteboard.PasteboardType(marker)]
            recorder.poll()
        }
        #expect(source.textReads == 0)
        #expect(source.typeReads == 5)
    }

    @Test func selfWritesAndUnstableSequencesAreNotRecorded() {
        let source = HistoryReaderFixture()
        var captured: [String] = []
        let recorder = ClipboardHistoryRecorder(reader: source, schedule: nil) { captured.append($0) }
        recorder.start()
        source.changeCount += 1
        source.text = "own copy"
        recorder.markSelfWrite()
        recorder.poll()
        #expect(source.textReads == 0)
        source.changeCount += 1
        source.afterTextRead = { source.changeCount += 1 }
        recorder.poll()
        #expect(captured.isEmpty)
        source.afterTextRead = nil
        source.text = "stable"
        recorder.poll()
        #expect(captured == ["stable"])
    }

    @Test func pasteboardsWithoutAdvertisedPlainTextAreNeverRead() {
        let source = HistoryReaderFixture()
        var captured: [String] = []
        let recorder = ClipboardHistoryRecorder(reader: source, schedule: nil) { captured.append($0) }
        recorder.start()
        for types: [NSPasteboard.PasteboardType] in [[], [.png], [.html]] {
            source.types = types
            source.changeCount += 1
            recorder.poll()
        }
        #expect(source.textReads == 0)
        #expect(captured.isEmpty)
    }

    @Test func pauseResumeOrClearDuringTypeOrTextReadInvalidatesTheInFlightCapture() {
        for phase in ["types", "text"] {
            for action in ["pause", "resume", "clear"] {
                let source = HistoryReaderFixture()
                var captured: [String] = []
                let recorder = ClipboardHistoryRecorder(reader: source, schedule: nil) { captured.append($0) }
                recorder.start()
                source.changeCount += 1
                let interrupt = {
                    switch action {
                    case "pause": recorder.stop()
                    case "resume": recorder.stop(); recorder.start()
                    default: recorder.markSelfWrite()
                    }
                }
                if phase == "types" { source.afterTypeRead = interrupt }
                else { source.afterTextRead = interrupt }
                recorder.poll()
                source.afterTypeRead = nil
                source.afterTextRead = nil
                #expect(captured.isEmpty, "\(action) during \(phase) reading must invalidate the pending payload")
                if phase == "types" { #expect(source.textReads == 0) }
                recorder.poll()
                #expect(captured.isEmpty)
                if !recorder.isRunning { recorder.start() }
                source.changeCount += 1
                source.text = "next change"
                recorder.poll()
                #expect(captured == ["next change"])
            }
        }
    }

    @Test func changedSequenceDuringTypeInspectionSkipsReadingTheNewPayload() {
        let source = HistoryReaderFixture()
        var captured: [String] = []
        let recorder = ClipboardHistoryRecorder(reader: source, schedule: nil) { captured.append($0) }
        recorder.start()
        source.changeCount += 1
        source.afterTypeRead = { source.changeCount += 1 }
        recorder.poll()
        #expect(source.textReads == 0)
        #expect(captured.isEmpty)
        source.afterTypeRead = nil
        recorder.poll()
        #expect(captured == ["fixture text"])
    }

    @Test func blankNulAndOversizePayloadsNeverReachTheHistorySink() {
        let source = HistoryReaderFixture()
        var captured: [String] = []
        let recorder = ClipboardHistoryRecorder(reader: source, schedule: nil) { captured.append($0) }
        recorder.start()
        for text in [" \n\t", "nul\0text", String(repeating: "中", count: 21_846)] {
            source.changeCount += 1
            source.text = text
            recorder.poll()
        }
        #expect(captured.isEmpty)
        source.changeCount += 1
        source.text = "  accepted\n"
        recorder.poll()
        #expect(captured == ["  accepted\n"])
    }

    @Test func timerStartsOnceAtHalfASecondAndIsCancelledOnPauseAndRelease() {
        let source = HistoryReaderFixture()
        let clock = HistoryScheduleFixture()
        var recorder: ClipboardHistoryRecorder? = ClipboardHistoryRecorder(reader: source, schedule: clock.schedule) { _ in }
        recorder?.start()
        recorder?.start()
        #expect(clock.intervals == [0.5])
        source.changeCount += 1
        clock.tick?()
        #expect(source.textReads == 1)
        recorder?.stop()
        #expect(clock.cancellations == 1)
        recorder?.start()
        #expect(clock.intervals == [0.5, 0.5])
        recorder = nil
        #expect(clock.cancellations == 2)
    }

    @Test func namedPasteboardModelStartsOffResumesFromBaselineAndClearDoesNotReingestOldText() throws {
        let pasteboard = NSPasteboard(name: .init("TCube-History-Test-\(UUID().uuidString)"))
        defer { pasteboard.releaseGlobally() }
        pasteboard.clearContents()
        #expect(pasteboard.setString("before enable", forType: .string))
        let model = ClipboardHistoryModel(pasteboard: pasteboard, schedulesPolling: false)
        #expect(!model.isEnabled)
        model.enable()
        model.poll()
        #expect(model.entries.isEmpty)
        pasteboard.clearContents()
        #expect(pasteboard.setString("  accepted\n", forType: .string))
        model.poll()
        #expect(model.entries.map(\.text) == ["  accepted\n"])
        model.pause()
        pasteboard.clearContents()
        #expect(pasteboard.setString("paused text", forType: .string))
        model.enable()
        model.poll()
        #expect(model.entries.map(\.text) == ["  accepted\n"])
        pasteboard.clearContents()
        #expect(pasteboard.setString("not yet polled", forType: .string))
        model.clear()
        model.poll()
        #expect(model.entries.isEmpty)
        model.shutdown()
        #expect(!model.isEnabled)
    }
}

@MainActor
private final class HistoryReaderFixture: ClipboardHistoryReading {
    var changeCount = 0
    var types: [NSPasteboard.PasteboardType] = [.string]
    var text: String? = "fixture text"
    var afterTextRead: (() -> Void)?
    var afterTypeRead: (() -> Void)?
    private(set) var textReads = 0
    private(set) var typeReads = 0
    var advertisedTypes: [NSPasteboard.PasteboardType] { typeReads += 1; afterTypeRead?(); return types }
    func readText() -> String? { textReads += 1; afterTextRead?(); return text }
}

@MainActor
private final class HistoryScheduleFixture {
    var intervals: [TimeInterval] = []
    var cancellations = 0
    var tick: (@MainActor () -> Void)?
    func schedule(interval: TimeInterval, tick: @escaping @MainActor () -> Void) -> AnyCancellable {
        intervals.append(interval)
        self.tick = tick
        return AnyCancellable { [weak self] in MainActor.assumeIsolated { self?.cancellations += 1 } }
    }
}
