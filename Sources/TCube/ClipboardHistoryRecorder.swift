import AppKit
import Combine
import CubeCore

@MainActor
protocol ClipboardHistoryReading: AnyObject {
    var changeCount: Int { get }
    var advertisedTypes: [NSPasteboard.PasteboardType] { get }
    func readText() -> String?
}

@MainActor
final class PasteboardHistoryReader: ClipboardHistoryReading {
    private let pasteboard: NSPasteboard
    init(pasteboard: NSPasteboard) { self.pasteboard = pasteboard }
    var changeCount: Int { pasteboard.changeCount }
    var advertisedTypes: [NSPasteboard.PasteboardType] { pasteboard.types ?? [] }
    func readText() -> String? { pasteboard.string(forType: .string) }
}

@MainActor
final class ClipboardHistoryRecorder {
    typealias Schedule = @MainActor (TimeInterval, @escaping @MainActor () -> Void) -> AnyCancellable
    static let pollingInterval: TimeInterval = 0.5
    private static let excludedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .fileURL, .init("NSFilenamesPboardType")
    ]
    private let reader: any ClipboardHistoryReading
    private let schedule: Schedule?
    private let receivedText: @MainActor (String) -> Void
    private var polling: AnyCancellable?
    private var lastSequence: Int?
    private var generation: UInt64 = 0
    private(set) var isRunning = false

    init(reader: any ClipboardHistoryReading, schedule: Schedule? = ClipboardHistoryRecorder.schedulePolling,
         receivedText: @escaping @MainActor (String) -> Void) {
        self.reader = reader
        self.schedule = schedule
        self.receivedText = receivedText
    }

    func start() {
        guard !isRunning else { return }
        generation &+= 1
        let startingGeneration = generation
        isRunning = true
        lastSequence = nil
        // Enabling or resuming never reads the clipboard's previous contents.
        let sequence = reader.changeCount
        guard isRunning else { return }
        if generation == startingGeneration { lastSequence = sequence }
        guard polling == nil else { return }
        let pending = schedule?(Self.pollingInterval, { [weak self] in self?.poll() })
        if isRunning, polling == nil { polling = pending }
        else { pending?.cancel() }
    }

    func stop() {
        generation &+= 1
        isRunning = false
        let previous = polling
        polling = nil
        lastSequence = nil
        previous?.cancel()
    }

    /// Called immediately after the app writes its own clipboard text, or clears history.
    func markSelfWrite() {
        generation &+= 1
        guard isRunning else { return }
        let markingGeneration = generation
        let sequence = reader.changeCount
        guard isRunning, generation == markingGeneration else { return }
        lastSequence = sequence
    }

    func poll() {
        guard isRunning, let lastSequence else { return }
        let readingGeneration = generation
        let sequence = reader.changeCount
        guard isRunning, generation == readingGeneration, sequence != lastSequence else { return }
        self.lastSequence = sequence
        let types = reader.advertisedTypes
        guard isCurrent(generation: readingGeneration, sequence: sequence), types.contains(.string),
              !types.contains(where: Self.excludedTypes.contains) else { return }
        let text = reader.readText()
        guard isCurrent(generation: readingGeneration, sequence: sequence), let text,
              ClipboardHistory.accepts(text) else { return }
        receivedText(text)
    }

    private func isCurrent(generation: UInt64, sequence: Int) -> Bool {
        guard isRunning, self.generation == generation else { return false }
        // Native pasteboard calls may run a nested event loop. Recheck state after
        // each call so pause, clear and resume invalidate any in-flight payload.
        let currentSequence = reader.changeCount
        return isRunning && self.generation == generation && currentSequence == sequence
    }

    static func schedulePolling(interval: TimeInterval, action: @escaping @MainActor () -> Void) -> AnyCancellable {
        let timer = Timer(timeInterval: interval, repeats: true) { _ in
            MainActor.assumeIsolated { action() }
        }
        RunLoop.main.add(timer, forMode: .common)
        // Releasing the recorder releases this token and invalidates its timer.
        return AnyCancellable { timer.invalidate() }
    }
}
